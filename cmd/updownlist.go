package cmd

import (
	"github.com/spf13/cobra"

	"github.com/virus-evolution/gofasta/pkg/gfio"
	"github.com/virus-evolution/gofasta/pkg/updown"
)

// updownListOptions holds the values of the flags of the command newUpdownListCmd returns
type updownListOptions struct {
	threads int
	strict  bool
}

func newUpdownListCmd() *cobra.Command {
	var o updownListOptions
	c := &cobra.Command{
		Use:   "list",
		Short: "Generate input CSV files for gofasta updown topranking",
		Long: `Generate input CSV files for gofasta updown topranking

Example usage:

	gofasta updown list -r root.fasta -q alignment.fasta -o mutationlist.csv

Non-ATGC nucleotides are not recommended in the --root, and --root and --query must be the same
width (either because --query was generated by alignment to --root, or because both have been aligned to a
third sequence, like a reference).

--outfile is a CSV-format file with the columns: query,SNPs,ambiguities,SNPcount,ambcount. There is one row
for each sequence in --query. SNPs is a "|"-delimited list of SNPs relative to --root. ambiguities is a
"|"-delimited list of ranges (1-based, inclusive) of tracts of ambiguities (anything that isn't ATGC).
`,

		PreRunE: func(cmd *cobra.Command, args []string) error {
			return firstError(
				intAtLeast(cmd, 0, "threads"),
				outputNotInput(cmd, "outfile", "query", "root"),
			)
		},
		RunE: func(cmd *cobra.Command, args []string) (err error) {

			root, err := openIn(cmd, "root")
			if err != nil {
				return err
			}
			defer root.Close()

			query, err := openIn(cmd, "query")
			if err != nil {
				return err
			}
			defer query.Close()

			out, err := openOut(cmd, "outfile")
			if err != nil {
				return err
			}
			defer gfio.CloseOut(out, &err)

			return updown.List(root, query, out, resolveThreads(o.threads), o.strict)
		},
	}

	c.Flags().StringP("query", "q", "stdin", "Alignment of sequences to parse, in fasta format")
	c.Flags().StringP("root", "r", "", "Root sequence, in fasta format, which is treated as the ancestor in the imaginary tree")
	addOutfileFlag(c, "the list, in CSV format")
	addStrictFlag(c, &o.strict)
	addThreadsFlag(c.Flags(), &o.threads)
	requireFlags(c, "root")
	c.Flags().SortFlags = false
	return c
}
